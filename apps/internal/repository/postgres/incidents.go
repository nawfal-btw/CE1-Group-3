// This file implements incident persistence with GORM. It maps database rows to domain types,
// but does not make incident lifecycle decisions.
package postgres

import (
	"context"
	"errors"
	"time"

	"github.com/google/uuid"
	domain "github.com/nawfal-btw/CE1-Group-3/apps/internal/domain"
	"gorm.io/gorm"
)

// ErrIncidentNotFound is returned when no incident exists with the requested ID.
var ErrIncidentNotFound = errors.New("incident not found")

// IncidentRepo stores and loads incidents in Postgres through GORM.
// It implements the application layer's IncidentRepository interface.
type IncidentRepo struct {
	db *gorm.DB
}

func NewIncidentRepo(db *gorm.DB) *IncidentRepo {
	return &IncidentRepo{db: db}
}

// Create inserts a new incident. The ID is generated by the domain, not by the database.
func (r *IncidentRepo) Create(ctx context.Context, i *domain.Incident) error {
	row := toRow(i)
	return r.db.WithContext(ctx).Create(&row).Error
}

// Get loads one incident by ID, or returns ErrIncidentNotFound.
func (r *IncidentRepo) Get(ctx context.Context, id domain.IncidentID) (*domain.Incident, error) {
	var row incidentRow
	err := r.db.WithContext(ctx).First(&row, "id = ?", uuid.UUID(id)).Error
	if errors.Is(err, gorm.ErrRecordNotFound) {
		return nil, ErrIncidentNotFound
	}
	if err != nil {
		return nil, err
	}
	return toDomain(row), nil
}

// Patch saves the already-patched incident (the domain has validated the changes).
// All columns are written, so a field that became unset is stored as NULL.
func (r *IncidentRepo) Patch(ctx context.Context, i *domain.Incident) error {
	row := toRow(i)
	result := r.db.WithContext(ctx).
		Model(&incidentRow{ID: row.ID}).
		Select("*").Omit("id").
		Updates(&row)
	if result.Error != nil {
		return result.Error
	}
	if result.RowsAffected == 0 {
		return ErrIncidentNotFound
	}
	return nil
}

// incidentRow is the database shape of an incident (one row in the "incidents" table).
// It is kept separate from domain.Incident so GORM tags never leak into the domain.
//
// Optional domain fields (Field[T] with Init=false) are stored as NULL, which is why
// most columns are pointers: nil <-> not set.
type incidentRow struct {
	ID       uuid.UUID `gorm:"column:id;type:uuid;primaryKey"`
	Type     *int16    `gorm:"column:type"`
	Status   *int8     `gorm:"column:status"`
	Priority *int8     `gorm:"column:priority"`

	// Location. Latitude and Longitude are either both set or both NULL.
	Latitude            *float64 `gorm:"column:latitude"`
	Longitude           *float64 `gorm:"column:longitude"`
	Address             *string  `gorm:"column:address"`
	ProximateLandmarks  []string `gorm:"column:proximate_landmarks;type:jsonb;serializer:json"`
	LocationDescription *string  `gorm:"column:location_description"`

	Description *string `gorm:"column:description"`

	CreatedAtUTC *time.Time `gorm:"column:created_at_utc"`
	UpdatedAtUTC *time.Time `gorm:"column:updated_at_utc"`
	ClosedAtUTC  *time.Time `gorm:"column:closed_at_utc"`

	Version string `gorm:"column:version"`
}

func (incidentRow) TableName() string {
	return "incidents"
}

// toRow converts a domain incident into its database row.
func toRow(i *domain.Incident) incidentRow {
	row := incidentRow{
		ID:       uuid.UUID(i.ID),
		Type:     fieldToPtr(i.Type, func(v domain.IncidentType) int16 { return int16(v) }),
		Status:   fieldToPtr(i.Status, func(v domain.IncidentStatus) int8 { return int8(v) }),
		Priority: fieldToPtr(i.Priority, func(v domain.IncidentPriority) int8 { return int8(v) }),

		Address:             fieldToPtr(i.Location.Address, same[string]),
		LocationDescription: fieldToPtr(i.Location.LocationDescription, same[string]),
		Description:         fieldToPtr(i.Description, same[string]),

		CreatedAtUTC: fieldToPtr(i.CreatedAtUTC, same[time.Time]),
		UpdatedAtUTC: fieldToPtr(i.UpdatedAtUTC, same[time.Time]),
		ClosedAtUTC:  fieldToPtr(i.ClosedAtUTC, same[time.Time]),

		Version: i.Version,
	}
	if i.Location.GIS.Init {
		lat, long := i.Location.GIS.Value.Latitude, i.Location.GIS.Value.Longitude
		row.Latitude, row.Longitude = &lat, &long
	}
	if i.Location.ProximateLandmarks.Init {
		row.ProximateLandmarks = i.Location.ProximateLandmarks.Value
	}
	return row
}

// toDomain converts a database row back into a domain incident.
func toDomain(row incidentRow) *domain.Incident {
	i := &domain.Incident{
		ID:       domain.IncidentID(row.ID),
		Type:     ptrToField(row.Type, func(v int16) domain.IncidentType { return domain.IncidentType(v) }),
		Status:   ptrToField(row.Status, func(v int8) domain.IncidentStatus { return domain.IncidentStatus(v) }),
		Priority: ptrToField(row.Priority, func(v int8) domain.IncidentPriority { return domain.IncidentPriority(v) }),

		Description: ptrToField(row.Description, same[string]),

		CreatedAtUTC: ptrToField(row.CreatedAtUTC, same[time.Time]),
		UpdatedAtUTC: ptrToField(row.UpdatedAtUTC, same[time.Time]),
		ClosedAtUTC:  ptrToField(row.ClosedAtUTC, same[time.Time]),

		Version: row.Version,
	}
	i.Location.Address = ptrToField(row.Address, same[string])
	i.Location.LocationDescription = ptrToField(row.LocationDescription, same[string])
	if row.Latitude != nil && row.Longitude != nil {
		i.Location.GIS = domain.Field[domain.LocationGIS]{
			Value: domain.LocationGIS{Latitude: *row.Latitude, Longitude: *row.Longitude},
			Init:  true,
		}
	}
	if row.ProximateLandmarks != nil {
		i.Location.ProximateLandmarks = domain.Field[[]string]{Value: row.ProximateLandmarks, Init: true}
	}
	return i
}

// fieldToPtr turns a domain Field into a nullable column value: not Init -> nil.
func fieldToPtr[T, C any](f domain.Field[T], conv func(T) C) *C {
	if !f.Init {
		return nil
	}
	v := conv(f.Value)
	return &v
}

// ptrToField turns a nullable column value into a domain Field: nil -> not Init.
func ptrToField[C, T any](p *C, conv func(C) T) domain.Field[T] {
	if p == nil {
		return domain.Field[T]{}
	}
	return domain.Field[T]{Value: conv(*p), Init: true}
}

func same[T any](v T) T { return v }
